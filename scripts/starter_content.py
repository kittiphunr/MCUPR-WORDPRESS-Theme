# ------------------------------------------------------------------ content helpers
def todo(text):
    return ('<p class="mcupr-todo"><strong>โครงร่างหน้า (Draft):</strong> ' + text +
            ' — ลบกล่องนี้ออกเมื่อแก้ไขเสร็จ</p>\n')

def ul(items):
    return '<ul>\n' + ''.join('<li>%s</li>\n' % i for i in items) + '</ul>\n'

def faq(pairs):
    return ''.join('<details><summary>%s</summary><p>%s</p></details>\n' % (q, a) for q, a in pairs)

def table(head, rows):
    h = '<thead><tr>' + ''.join('<th scope="col">%s</th>' % c for c in head) + '</tr></thead>'
    b = '<tbody>' + ''.join('<tr>' + ''.join('<td>%s</td>' % c for c in r) + '</tr>' for r in rows) + '</tbody>'
    return '<table>' + h + b + '</table>\n'

