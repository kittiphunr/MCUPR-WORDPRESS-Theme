#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Writes mcupr/inc/admin-th-strings.php (English admin text -> Thai) from scripts/admin_th.py."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from admin_th import TH

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"

out = ["<?php\n/**\n * Thai text for the admin / Customizer strings of the theme (generated by scripts/make-admin-th.py\n * from scripts/admin_th.py – edit that file, not this one).\n *\n * @package MCUPR\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn array(\n"]
for k in sorted(TH):
    out.append("\t%s => %s,\n" % (q(k), q(TH[k])))
out.append(");\n")
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'mcupr', 'inc', 'admin-th-strings.php')
open(dest, 'w', encoding='utf-8').write(''.join(out))
print('wrote', len(TH), 'strings')
