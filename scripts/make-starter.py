#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build mcupr/starter/mcupr-starter.xml (WXR 1.2) from starter_content.py.

    python3 scripts/make-starter.py

Import with Tools -> Import -> WordPress (the WordPress Importer plugin). Pages are published, translated titles
(en/zh/ja) are stored as _mcupr_{lang}_title post meta, and menus are assigned to their theme locations
automatically (term meta _mcupr_location, see inc/menus.php).
"""
import os
import sys
from xml.sax.saxutils import escape

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import starter_content as S  # noqa: E402

SITE = 'https://example.org'
NOW = '2025-01-01 09:00:00'
out = []
nid = [100]


def cd(s):
    return '<![CDATA[%s]]>' % str(s).replace(']]>', ']]]]><![CDATA[>')


def meta(k, v):
    return '\t\t<wp:postmeta><wp:meta_key>%s</wp:meta_key><wp:meta_value>%s</wp:meta_value></wp:postmeta>\n' % (escape(k), cd(v))


def next_id():
    nid[0] += 1
    return nid[0]


PAGE_ID = {}
CAT_ID = {}
order = []  # page keys, parents first
for r in S.ROOTS:
    order.append(r)
    order += S.SECTIONS.get(r, [])
for k in S.T:
    if k not in order:
        order.append(k)
for k in order:
    PAGE_ID[k] = next_id()
for i, (slug, name) in enumerate(S.CATEGORIES):
    CAT_ID[slug] = 10 + i

MENUS = [
    ('primary_th', 'main-th', 'เมนูหลัก (ไทย)', S.MAIN, 0),
    ('primary_en', 'main-en', 'Main menu (English)', S.MAIN, 1),
    ('primary_zh', 'main-zh', 'Main menu (中文)', S.MAIN, 2),
    ('primary_ja', 'main-ja', 'Main menu (日本語)', S.MAIN, 3),
    ('footer', 'footer-links', 'Footer links', S.FOOTER, 0),
    ('quick', 'quick-links', 'Quick links', S.QUICK, 0),
    ('utility', 'utility-links', 'Utility bar links', S.UTILITY, 0),
]

out.append('<?xml version="1.0" encoding="UTF-8" ?>\n')
out.append('<!-- MCUPR starter content: government-style pages + menus. Generated by scripts/make-starter.py -->\n')
out.append('<rss version="2.0" xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/" xmlns:content="http://purl.org/rss/1.0/modules/content/" '
           'xmlns:wfw="http://wellformedweb.org/CommentAPI/" xmlns:dc="http://purl.org/dc/elements/1.1/" xmlns:wp="http://wordpress.org/export/1.2/">\n<channel>\n')
out.append('<title>MCUPR starter</title>\n<link>%s</link>\n<description></description>\n<pubDate>Wed, 01 Jan 2025 09:00:00 +0000</pubDate>\n'
           '<language>th</language>\n<wp:wxr_version>1.2</wp:wxr_version>\n<wp:base_site_url>%s</wp:base_site_url>\n<wp:base_blog_url>%s</wp:base_blog_url>\n' % (SITE, SITE, SITE))

for slug, name in S.CATEGORIES:
    out.append('<wp:category><wp:term_id>%d</wp:term_id><wp:category_nicename>%s</wp:category_nicename><wp:category_parent></wp:category_parent>'
               '<wp:cat_name>%s</wp:cat_name></wp:category>\n' % (CAT_ID[slug], slug, cd(name)))

for n, (slug, (nm, _en)) in enumerate(S.WORK_CATS):
    out.append('<wp:term><wp:term_id>%d</wp:term_id><wp:term_taxonomy>mcupr_work_cat</wp:term_taxonomy><wp:term_slug>%s</wp:term_slug><wp:term_name>%s</wp:term_name></wp:term>\n' % (30 + n, slug, cd(nm)))

for loc, slug, name, _items, _li in MENUS:
    out.append('<wp:term><wp:term_id>%d</wp:term_id><wp:term_taxonomy>nav_menu</wp:term_taxonomy><wp:term_slug>%s</wp:term_slug><wp:term_name>%s</wp:term_name>'
               '<wp:termmeta><wp:meta_key>_mcupr_location</wp:meta_key><wp:meta_value>%s</wp:meta_value></wp:termmeta></wp:term>\n'
               % (50 + [m[0] for m in MENUS].index(loc), slug, cd(name), cd(loc)))


def item_head(pid, title, slug, ptype, parent=0, order_=0, content='', status='publish', excerpt=''):
    return ('<item>\n\t<title>%s</title>\n\t<link>%s/?p=%d</link>\n\t<pubDate>Wed, 01 Jan 2025 09:00:00 +0000</pubDate>\n\t<dc:creator>%s</dc:creator>\n'
            '\t<guid isPermaLink="false">%s/?p=%d</guid>\n\t<description></description>\n\t<content:encoded>%s</content:encoded>\n\t<excerpt:encoded>%s</excerpt:encoded>\n'
            '\t<wp:post_id>%d</wp:post_id>\n\t<wp:post_date>%s</wp:post_date>\n\t<wp:post_date_gmt>%s</wp:post_date_gmt>\n\t<wp:post_modified>%s</wp:post_modified>\n'
            '\t<wp:post_modified_gmt>%s</wp:post_modified_gmt>\n\t<wp:comment_status>closed</wp:comment_status>\n\t<wp:ping_status>closed</wp:ping_status>\n'
            '\t<wp:post_name>%s</wp:post_name>\n\t<wp:status>%s</wp:status>\n\t<wp:post_parent>%d</wp:post_parent>\n\t<wp:menu_order>%d</wp:menu_order>\n'
            '\t<wp:post_type>%s</wp:post_type>\n\t<wp:post_password></wp:post_password>\n\t<wp:is_sticky>0</wp:is_sticky>\n'
            % (cd(title), SITE, pid, cd('admin'), SITE, pid, cd(content), cd(excerpt), pid, NOW, NOW, NOW, NOW, cd(slug), status, parent, order_, ptype))


# ---- pages
for n, k in enumerate(order):
    th, en, zh, ja = S.T[k]
    parent = PAGE_ID[S.PARENT[k]] if k in S.PARENT else 0
    out.append(item_head(PAGE_ID[k], th, k, 'page', parent, n, S.C.get(k, '')))
    out.append(meta('_mcupr_en_title', en) + meta('_mcupr_zh_title', zh) + meta('_mcupr_ja_title', ja))
    if k in S.EN_BODY:
        out.append(meta('_mcupr_en_content', S.EN_BODY[k]))
    out.append('</item>\n')


# ---- sample events (custom post type of the theme)
import datetime  # noqa: E402
for n, (days, t0, t1, title, place) in enumerate(S.EVENTS):
    d = (datetime.date.today() + datetime.timedelta(days=days)).isoformat()
    pid = next_id()
    out.append(item_head(pid, title[0], 'event-%d' % (n + 1), 'mcupr_event', 0, 0, '<p>[รายละเอียดกิจกรรม]</p>', 'publish'))
    out.append(meta('_mcupr_en_title', title[1]) + meta('_mcupr_zh_title', title[2]) + meta('_mcupr_ja_title', title[3]))
    if t0:
        out.append(meta('_mcupr_ev_start', '%s %s:00' % (d, t0)) + meta('_mcupr_ev_end', '%s %s:00' % (d, t1)))
    else:
        out.append(meta('_mcupr_ev_start', d + ' 00:00:00') + meta('_mcupr_ev_end', d + ' 23:59:59') + meta('_mcupr_ev_allday', 1))
    out.append(meta('_mcupr_ev_place', place))
    out.append('</item>\n')


# ---- administration chart units + sample works (own post types and categories)
UNIT_ID = {}
for key, parent, order_, title, person, role in S.UNITS:
    UNIT_ID[key] = next_id()
for key, parent, order_, title, person, role in S.UNITS:
    out.append(item_head(UNIT_ID[key], title[0], 'unit-' + key, 'mcupr_unit', UNIT_ID[parent] if parent else 0, order_, '', 'publish'))
    out.append(meta('_mcupr_en_title', title[1]) + meta('_mcupr_zh_title', title[2]) + meta('_mcupr_ja_title', title[3]))
    if person:
        out.append(meta('_mcupr_unit_person', person))
    if role:
        out.append(meta('_mcupr_unit_role', role))
    out.append('</item>\n')

for slug, (nm, _en) in S.WORK_CATS:
    pass
for n, (title, event, award, yoff, org, cat, team) in enumerate(S.WORKS):
    pid = next_id()
    out.append(item_head(pid, title[0], 'work-%d' % (n + 1), 'mcupr_work', 0, 0, '<p>[รายละเอียดผลงาน เล่าที่มา ผู้ร่วมงาน และผลที่ได้รับ]</p>', 'publish'))
    out.append('\t<category domain="mcupr_work_cat" nicename="%s">%s</category>\n' % (cat, cd(dict(S.WORK_CATS)[cat][0])))
    out.append(meta('_mcupr_en_title', title[1]))
    out.append(meta('_mcupr_work_event', event) + meta('_mcupr_work_award', award) + meta('_mcupr_work_year', datetime.date.today().year + yoff) + meta('_mcupr_work_org', org) + meta('_mcupr_work_team', team.replace('\\n', '\n')))
    out.append('</item>\n')


# ---- menu items
def emit_items(menu_slug, menu_name, loc, items, li):
    seq = [0]

    def walk(lst, parent_id):
        for it in lst:
            seq[0] += 1
            pid = next_id()
            t = it['target']
            label = it['label'][li]
            if t[0] == 'page':
                typ, obj, oid, url = 'post_type', 'page', PAGE_ID[t[1]], ''
            elif t[0] == 'cat':
                typ, obj, oid, url = 'taxonomy', 'category', CAT_ID[t[1]], ''
            else:
                typ, obj, oid, url = 'custom', 'custom', pid, ('#' if t[0] == 'label' else t[1])
            out.append(item_head(pid, label, 'menu-%s-%d' % (menu_slug, seq[0]), 'nav_menu_item', 0, seq[0], '', 'publish'))
            out.append('\t<category domain="nav_menu" nicename="%s">%s</category>\n' % (menu_slug, cd(menu_name)))
            classes = []
            if it.get('icon'):
                classes.append('mcupr-icon-' + it['icon'])
            if it.get('mega'):
                classes.append('mcupr-mega-%d' % it['mega'])
            cls = 'a:%d:{%s}' % (max(len(classes), 1), ''.join('i:%d;s:%d:"%s";' % (n, len(c), c) for n, c in enumerate(classes or [''])))
            out.append(meta('_menu_item_type', typ) + meta('_menu_item_menu_item_parent', parent_id) + meta('_menu_item_object_id', oid) +
                       meta('_menu_item_object', obj) + meta('_menu_item_target', '') + meta('_menu_item_classes', cls) +
                       meta('_menu_item_xfn', '') + meta('_menu_item_url', url))
            out.append('</item>\n')
            walk(it['kids'], pid)

    walk(items, 0)


for loc, slug, name, items, li in MENUS:
    emit_items(slug, name, loc, items, li)

out.append('</channel>\n</rss>\n')
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'mcupr', 'starter', 'mcupr-starter.xml')
with open(dest, 'w', encoding='utf-8') as f:
    f.write(''.join(out))
print('wrote', os.path.normpath(dest), '- %d pages, %d menus, %d ids' % (len(order), len(MENUS), nid[0] - 100))
